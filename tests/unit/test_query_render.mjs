/**
 * Regression and Unit tests for Codebase Query UI rendering (Graph RAG).
 * Validates DOM generation, groundedness badges, source pills, confidence, error boundaries,
 * and malformed payload handling.
 */

import assert from "node:assert";
import { test } from "node:test";
import {
  escapeAttr,
  escapeHtml,
  renderMarkdown,
  renderQueryResponse,
} from "../../frontend/js/query.js";

function createMockContainer() {
  const listeners = [];
  return {
    innerHTML: "",
    querySelectorAll(selector) {
      // Mock selector for source pills
      const matches = [];
      const regex = /class="source-pill"[^>]*data-source="([^"]+)"/g;
      let m;
      while ((m = regex.exec(this.innerHTML)) !== null) {
        const sourcePath = m[1];
        matches.push({
          dataset: { source: sourcePath },
          addEventListener(event, fn) {
            listeners.push({ event, sourcePath, fn });
          },
        });
      }
      return matches;
    },
    _listeners: listeners,
  };
}

test("1. Successful HTTP 200 response renders complete answer, confidence, and validated badge", () => {
  const container = createMockContainer();
  const sampleResponse = {
    answer: "### Direct Answer\nNeo4jClient manages database connections using lazy initialization in `app/graph/neo4j_client.py:15-60`.\n\n### Explanation\nThe client verifies connectivity.",
    confidence: 0.9,
    validation_status: true,
    validation_errors: [],
    sources: ["app/graph/neo4j_client.py", "app/graph/graph_builder.py"],
    graph_paths: [
      {
        source_node: { id: "n1", name: "Neo4jClient" },
        target_node: { id: "n2", name: "GraphBuilder" },
        relationships: ["USED_BY"],
      },
    ],
    debug_info: {
      query_intent: "general_code_question",
      resolved_entities: ["Neo4jClient"],
      graph_results_count: 5,
      semantic_results_count: 5,
      fused_results: [{}, {}, {}],
      subgraph_stats: { nodes: 10, edges: 15 },
    },
  };

  renderQueryResponse(sampleResponse, container);

  assert.ok(container.innerHTML.includes('id="answer-container"'), "Must render answer-container element");
  assert.ok(container.innerHTML.includes('id="answer-text"'), "Must render answer-text element");
  assert.ok(container.innerHTML.includes('Direct Answer'), "Must render direct answer heading");
  assert.ok(container.innerHTML.includes('Confidence: 90%'), "Must render 90% confidence tag");
  assert.ok(container.innerHTML.includes('id="validation-badge"'), "Must render validation-badge element");
  assert.ok(container.innerHTML.includes("Grounded Evidence Validated"), "Must render Grounded Evidence Validated badge");
  assert.ok(!container.innerHTML.includes("warning"), "Validated answer must not have warning class");
  assert.ok(container.innerHTML.includes("VERIFIED CODEBASE CITATIONS (2)"), "Must render citation count");
  assert.ok(container.innerHTML.includes("app/graph/neo4j_client.py"), "Must render citation file path");
  assert.ok(container.innerHTML.includes("app/graph/graph_builder.py"), "Must render second citation file path");
  assert.ok(container.innerHTML.includes('id="debug-trace-container"'), "Must render debug trace container");
  assert.ok(container.innerHTML.includes("Resolved Entities:</strong> Neo4jClient"), "Must render resolved entities");
});

test("2. Ungrounded response renders warning status badge and detailed violation notices", () => {
  const container = createMockContainer();
  const warningResponse = {
    answer: "Payment processing is handled in unverified_payment_service.py:100.",
    confidence: 0.5,
    validation_status: false,
    validation_errors: ["Answer cited ungrounded file path: 'unverified_payment_service.py'"],
    sources: ["app/services/order_service.py"],
    graph_paths: [],
  };

  renderQueryResponse(warningResponse, container);

  assert.ok(container.innerHTML.includes('id="answer-container"'), "Must render answer-container");
  assert.ok(container.innerHTML.includes("status-badge warning"), "Must render warning badge class");
  assert.ok(container.innerHTML.includes("Grounding Notice:"), "Must display grounding notice summary");
  assert.ok(
    container.innerHTML.includes("unverified_payment_service.py"),
    "Must preserve and display specific ungrounded citation error"
  );
  assert.ok(container.innerHTML.includes("Confidence: 50%"), "Must render 50% confidence tag");
});

test("3. Empty or null answer handles fallback gracefully without breaking DOM", () => {
  const container = createMockContainer();
  const emptyResponse = {
    answer: "",
    confidence: 0.0,
    validation_status: false,
    validation_errors: ["No answer generated by LLM provider."],
    sources: [],
    graph_paths: [],
  };

  renderQueryResponse(emptyResponse, container);

  assert.ok(container.innerHTML.includes('id="answer-container"'), "Must render answer-container");
  assert.ok(
    container.innerHTML.includes("No answer could be generated from the available codebase context."),
    "Must display polite informative fallback message"
  );
  assert.ok(container.innerHTML.includes("No direct file citations returned"), "Must handle zero sources gracefully");
});

test("4. Fenced code blocks and formatting render properly in renderMarkdown", () => {
  const rawText = "```python\ndef connect():\n    return Neo4jClient()\n```\n- Point 1\n- Point 2";
  const rendered = renderMarkdown(rawText);

  assert.ok(rendered.includes("<pre"), "Must wrap code blocks in <pre>");
  assert.ok(rendered.includes("<code>def connect():"), "Must wrap code in <code>");
  assert.ok(rendered.includes("<li"), "Must render bullet points as <li>");
});

test("5. Malformed response with missing fields does not throw exceptions", () => {
  const container = createMockContainer();
  const malformedResponse = {
    // missing answer, sources, confidence, validation_status
  };

  assert.doesNotThrow(() => {
    renderQueryResponse(malformedResponse, container);
  });
  assert.ok(container.innerHTML.includes('id="answer-container"'));
});

test("6. Null container or null response returns safely", () => {
  assert.doesNotThrow(() => {
    renderQueryResponse(null, createMockContainer());
    renderQueryResponse({}, null);
  });
});
